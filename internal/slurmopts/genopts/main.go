// Command genopts regenerates the slurmopts option tables from SchedMD's HTML
// man pages, for a new SLURM release:
//
//	v=24.05
//	for c in sbatch srun salloc squeue sacct scancel scontrol sinfo; do
//	  curl -fsSL -o /tmp/man/$c.html https://slurm.schedmd.com/archive/slurm-$v-latest/$c.html
//	done
//	go run ./internal/slurmopts/genopts -out internal/slurmopts/slurm-$v /tmp/man/*.html
//
// The command name is the file's base name. Review the diff before committing:
// it is the shim's record of what SLURM accepts.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/hpc-gridware/slurm-shim/internal/slurmopts"
)

// manPageFixes are options whose man-page heading omits the value notation
// although the command requires one (checked against sacct --help and the
// option descriptions, SLURM 24.05). Keyed by command and the option's first
// spelling.
var manPageFixes = map[string]map[string]slurmopts.Kind{
	"sacct": {
		"-o": slurmopts.Required, // --format=<list>
		"-S": slurmopts.Required, // --starttime=<time>
		"-K": slurmopts.Required, // --timelimit-max=<time>
		"-k": slurmopts.Required, // --timelimit-min=<time>
		"-q": slurmopts.Required, // --qos=<list>
		"-r": slurmopts.Required, // --partition=<list>
	},
}

func main() {
	out := flag.String("out", "", "directory to write <command>.txt into")
	flag.Parse()
	if *out == "" || flag.NArg() == 0 {
		fmt.Fprintln(os.Stderr, "usage: genopts -out DIR MANPAGE.html...")
		os.Exit(2)
	}
	for _, path := range flag.Args() {
		page, err := os.ReadFile(path)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		cmd := strings.TrimSuffix(filepath.Base(path), filepath.Ext(path))
		opts := slurmopts.ParseManPage(string(page))
		for i, o := range opts {
			if k, ok := manPageFixes[cmd][o.Names[0]]; ok {
				opts[i].Value = k
			}
		}
		sort.Slice(opts, func(i, j int) bool { return opts[i].Names[0] < opts[j].Names[0] })
		header := "# Generated by genopts from the SLURM man page of " + cmd + ". Do not edit.\n"
		if err := os.WriteFile(filepath.Join(*out, cmd+".txt"), []byte(header+slurmopts.FormatTable(opts)), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "%s: %d options\n", cmd, len(opts))
	}
}
